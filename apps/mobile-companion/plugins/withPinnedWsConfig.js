// Config plugin for the DSH Companion app (A031).
//
// What it guarantees for `npx expo prebuild` (both platforms), derived from `app.json`:
//
// Android
//   * `android:usesCleartextTraffic="false"` is AUTHORED HERE, on the generated
//     `<application>`: Expo's app config has no `android.usesCleartextTraffic` field (expo-doctor
//     and EAS reject it as an additional property), so nothing can carry it from app.json into
//     the manifest. An unset attribute is set to "false"; an attribute some other plugin or a
//     hand-edited manifest already set to anything but "false" is a hard error — it is never
//     silently trusted, and it is never quietly overwritten with a weaker value either.
//   * `android:networkSecurityConfig="@xml/network_security_config"` points at a generated
//     `res/xml/network_security_config.xml` whose base-config is
//     `cleartextTrafficPermitted="false"` with NO `<certificates>` overrides: system CAs are not
//     trusted (the gateway leaf is pinned in code by `modules/pinned-ws`), user-installed CAs
//     are explicitly refused, and cleartext is off. This is defence in depth on top of the pin,
//     not a replacement for it. Note Android 7.0+ (API 24+, all supported targets) uses the
//     network security config's `cleartextTrafficPermitted` and ignores
//     `android:usesCleartextTraffic`; both are kept so neither can be the weak link.
//   * Explicit `android.usesCleartextTraffic` in app.json is rejected at config time with an
//     actionable message: the field is unsupported (EAS's expo-doctor run fails on it) and the
//     plugin sets the manifest attribute itself.
//
// iOS
//   * app.json must not add ATS exceptions: `NSAllowsArbitraryLoads` and `NSExceptionDomains`
//     are rejected before any mod runs (the pinned WSS connection is made by
//     URLSessionWebSocketTask with a trust-pinned delegate; ATS exceptions would only weaken
//     other traffic). Expo's own template defaults are left untouched.
//   * `vi.lproj/InfoPlist.strings` and `en.lproj/InfoPlist.strings` are written under
//     `ios/<ProjectName>/` with localised camera / Face ID usage strings, so the system
//     permission prompt is translated (the English-only prompt noted in
//     `specs/002-companion-app/tasks.md`). The
//     English values repeat `app.json`'s Info.plist strings, so `expo config` and the bundle
//     agree. Writing the files is not enough (A033): a `.lproj` directory Xcode does not know
//     about is never copied into the bundle, so the `ios.xcodeproj` mod also registers them as
//     an `InfoPlist.strings` `PBXVariantGroup` in the app group, with one
//     `<locale>.lproj/InfoPlist.strings` file reference per locale and a single `Resources`
//     build-phase entry. That registration is idempotent (running prebuild again adds nothing)
//     and reuses/cleans a plain non-variant registration of the same paths instead of leaving a
//     duplicate copy in the bundle. Requires the `expo` `ios.xcodeproj` base mod (a real
//     prebuild); introspection drops it, like every non-introspective mod.
//
// The pure helpers below (`applyNetworkSecurityConfig`, `assertAtsDefaults`, `writeLocales`,
// `registerLocalisedInfoPlist`) contain all the logic; the `with*` wrappers only connect them to
// prebuild's mod system, which keeps them unit-testable without a native project
// (`test/config-plugin.test.ts`).
//
// Registered in `app.json` `expo.plugins` as `"./plugins/withPinnedWsConfig"`.

