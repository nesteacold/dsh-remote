/**
 * Register the `<locale>.lproj/InfoPlist.strings` files in `project.pbxproj` (A033). The mod runs
 * after the dangerous one (prebuild orders `dangerous` before `xcodeproj`), so the files it
 * registers have already been written. Introspection drops non-introspective mods, so
 * `expo config --type introspect` never needs an `ios/` project.
 */
const withLocalisedPermissionStringsRegistered = (config, resolved) => {
  const locales = resolved.locales.filter((locale) => resolved.strings[locale]);
  if (locales.length === 0) return config;
  return withXcodeProject(config, (config) => {
    const project = config.modResults;
    if (!project || typeof project.getTarget !== 'function') {
      throw new Error(`${PLUGIN_NAME}: the ios.xcodeproj mod did not provide a parsed Xcode project`);
    }
    registerLocalisedInfoPlist(project, config.modRequest.projectName, locales);
    return config;
  });
};

