/** Serialise a `.strings` file: `"key" = "value";` per line, quotes and backslashes escaped. */
function stringsFileContent(values) {
  const escape = (text) => String(text).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  const lines = Object.keys(values)
    .filter((key) => typeof values[key] === 'string' && values[key].length > 0)
    .map((key) => `"${escape(key)}" = "${escape(values[key])}";`);
  return `/* Generated by apps/mobile-companion/plugins/withPinnedWsConfig.js (A031). */\n${lines.join('\n')}\n`;
}

