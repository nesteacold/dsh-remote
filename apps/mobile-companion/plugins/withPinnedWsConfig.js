/**
 * Config helper: app.json must not try to steer cleartext through the (unsupported) Expo field.
 *
 * `android.usesCleartextTraffic` is not part of Expo's app config schema — expo-doctor (and with
 * it `eas build`) fails with "additional property", and the value never reaches the manifest. The
 * plugin writes `android:usesCleartextTraffic="false"` into the generated manifest instead, so
 * any presence of the field is either a stale copy of the old setup (even `false`) or an actual
 * attempt to enable HTTP; both fail here, at config time, with the fix in the message.
 */
function assertNoCleartextOptIn(config) {
  const android = config && config.android;
  if (!android || android.usesCleartextTraffic === undefined) return;
  const value = JSON.stringify(android.usesCleartextTraffic) ?? String(android.usesCleartextTraffic);
  throw new Error(
    `${PLUGIN_NAME}: app.json must not set android.usesCleartextTraffic (found ${value}); ` +
      'Expo does not support that app config field (expo-doctor / eas build reject it) and ' +
      'cleartext HTTP is never allowed. Remove it: this plugin writes ' +
      'android:usesCleartextTraffic="false" into the generated AndroidManifest.xml itself.',
  );
}

/**
 * Manifest helper: author `android:usesCleartextTraffic="false"`, point the application at the
 * generated network security config, and throw when either is already set to something else.
 *
 * - attribute absent  -> the standard `expo prebuild` state (Expo leaves it out); set it.
 * - attribute "false" -> keep it (normalised to the string form).
 * - anything else     -> explicit unsafe override (another config plugin such as
 *                        expo-build-properties, or a hand-edited manifest); fail loudly.
 */
function applyNetworkSecurityConfig(manifest) {
  const application = manifest && manifest.manifest && manifest.manifest.application && manifest.manifest.application[0];
  if (!application) {
    throw new Error(`${PLUGIN_NAME}: AndroidManifest.xml has no <application>`);
  }
  if (!application.$) application.$ = {};
  const attributes = application.$;
  const cleartext = attributes['android:usesCleartextTraffic'];
  if (cleartext === undefined) {
    attributes['android:usesCleartextTraffic'] = 'false';
  } else if (cleartext !== 'false' && cleartext !== false) {
    throw new Error(
      `${PLUGIN_NAME}: AndroidManifest.xml sets android:usesCleartextTraffic="${String(cleartext)}"; ` +
        'it must be "false" (or absent, in which case this plugin sets it). The pinned WSS ' +
        'transport never needs cleartext, and plain HTTP would bypass the certificate pin.',
    );
  } else {
    attributes['android:usesCleartextTraffic'] = 'false';
  }
  if (attributes['android:networkSecurityConfig'] !== undefined
    && attributes['android:networkSecurityConfig'] !== `@xml/${NETWORK_SECURITY_CONFIG_NAME}`) {
    throw new Error(
      `${PLUGIN_NAME}: the app must not point at a different network security config ` +
        `(found ${String(attributes['android:networkSecurityConfig'])})`,
    );
  }
  attributes['android:networkSecurityConfig'] = `@xml/${NETWORK_SECURITY_CONFIG_NAME}`;
  return manifest;
}

/** Write `res/xml/network_security_config.xml` under an Android project root. */
function writeNetworkSecurityConfig(projectRoot) {
  const xmlDir = path.join(projectRoot, 'android', 'app', 'src', 'main', 'res', 'xml');
  fs.mkdirSync(xmlDir, { recursive: true });
  const target = path.join(xmlDir, `${NETWORK_SECURITY_CONFIG_NAME}.xml`);
  fs.writeFileSync(target, NETWORK_SECURITY_CONFIG_XML, 'utf8');
  return target;
}

/**
 * Info.plist helper: refuse ATS exceptions. Returns the plist unchanged otherwise.
 *
 * Run this on the app.json-provided Info.plist, never on the merged `modResults`: when there is
 * no `ios/` project yet, Expo's introspection base mod supplies its own dev defaults
 * (`NSAllowsArbitraryLoads: true` plus a `localhost` exception). A real prebuild starts from the
 * Expo template (`NSAllowsArbitraryLoads: false`, `NSAllowsLocalNetworking: true`), but the
 * introspection defaults are not an app.json opt-in and must not be mistaken for one — otherwise
 * `expo config --type introspect` (and anything that resolves config that way) fails.
 */
function assertAtsDefaults(infoPlist) {
  const ats = infoPlist.NSAppTransportSecurity;
  if (ats && (ats.NSAllowsArbitraryLoads === true || ats.NSExceptionDomains !== undefined)) {
    throw new Error(
      `${PLUGIN_NAME}: app.json must not add ATS exceptions (NSAllowsArbitraryLoads / NSExceptionDomains); ` +
        'the pinned transport needs none',
    );
  }
  return infoPlist;
}

/** Config helper: check only the app.json `ios.infoPlist` for ATS opt-ins. */
function assertNoAtsOptIn(config) {
  const infoPlist = (config && config.ios && config.ios.infoPlist) || {};
  assertAtsDefaults(infoPlist);
}

/** Write `<ProjectName>/<locale>.lproj/InfoPlist.strings` for every requested locale. */
function writeLocales(projectRoot, projectName, locales, strings) {
  if (!projectName) throw new Error(`${PLUGIN_NAME}: iOS project name is unknown`);
  if (!/^[A-Za-z0-9_]+$/.test(projectName)) throw new Error(`${PLUGIN_NAME}: unexpected iOS project name`);
  const targetDir = path.join(projectRoot, 'ios', projectName);
  const written = [];
  for (const locale of locales) {
    const values = strings[locale];
    if (!values) continue;
    // Locale folder names are language tags: letters, digits and dashes only.
    if (!/^[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})*$/.test(locale)) {
      throw new Error(`${PLUGIN_NAME}: unsupported locale "${locale}"`);
    }
    const lproj = path.join(targetDir, `${locale}.lproj`);
    fs.mkdirSync(lproj, { recursive: true });
    const target = path.join(lproj, 'InfoPlist.strings');
    fs.writeFileSync(target, stringsFileContent(values), 'utf8');
    written.push(target);
  }
  return written;
}

// ---------------------------------------------------------------------------
// Xcode project registration (A033)
//
// `expo prebuild` copies a resource only when the generated `.xcodeproj` references it. The
// `.strings` files above therefore have to be registered in `project.pbxproj`; otherwise the
// `.lproj` folders sit in `ios/<ProjectName>/` and never reach the app bundle. Xcode's own
// representation for a localised Info.plist is a `PBXVariantGroup` named `InfoPlist.strings`
// inside the app group, whose children are `<locale>` file references pointing at
// `<locale>.lproj/InfoPlist.strings`, plus ONE build file in the Resources build phase. The
// helpers below build exactly that, through the `xcode` instance Expo hands the `ios.xcodeproj`
// mod, and are idempotent so a second prebuild over an existing project changes nothing.
// ---------------------------------------------------------------------------

const IOS_VARIANT_GROUP_NAME = 'InfoPlist.strings';
const IOS_RESOURCES_BUILD_PHASE = 'Resources';
const APPLICATION_PRODUCT_TYPE = 'com.apple.product-type.application';
const XCODE_LOCALE_PATTERN = /^[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})*$/;

/**
 * `xcode` keeps parsed pbxproj scalars as written, quotes included (`"en"`), while objects it
 * creates itself may hold unquoted values. Compare both forms through this.
 */
function unquoteXcodeValue(value) {
  return typeof value === 'string' ? value.replace(/^"(.*)"$/, '$1') : value;
}

/** One parsed xcode project section (`PBXGroup`, `PBXFileReference`, ...), comments excluded. */
function xcodeSectionEntries(project, isa) {
  const section = (project.hash && project.hash.project && project.hash.project.objects
    && project.hash.project.objects[isa]) || {};
  return Object.keys(section)
    .filter((key) => !key.endsWith('_comment'))
    .map((key) => ({ key, object: section[key] }));
}

/**
 * Locate the group holding the app target's files (`ios/<ProjectName>`) and its directory
 * relative to `ios/`, so file references can be written relative to that group.
 *
 * Xcode's template stores it as a `PBXGroup` with `name`/`path` `<ProjectName>` under the main
 * group, whose children then use `<locale>.lproj/...` paths. Only `<group>` source trees are
 * accumulated; a project without such a group falls back to the main group, whose directory is
 * `ios/` itself (children then carry the full `<ProjectName>/...` path).
 */
function locateIosAppGroup(project, projectName) {
  const { firstProject } = project.getFirstProject();
  const mainGroupKey = unquoteXcodeValue(firstProject.mainGroup);
  const mainGroup = project.getPBXGroupByKey(mainGroupKey);
  const mainDirectory = mainGroup ? unquoteXcodeValue(mainGroup.path) || '' : '';
  const joinDirectory = (directory, component) => (directory ? `${directory}/${component}` : component);
  let found = null;
  const visited = new Set();
  const visit = (key, directory) => {
    if (found || visited.has(key)) return;
    visited.add(key);
    const group = project.getPBXGroupByKey(key);
    if (!group || !Array.isArray(group.children)) return;
    const groupPath = unquoteXcodeValue(group.path) || '';
    const groupDirectory = groupPath ? joinDirectory(directory, groupPath) : directory;
    const groupName = unquoteXcodeValue(group.name) || groupPath;
    if (groupName === projectName || groupPath === projectName) {
      found = { key, directory: groupDirectory };
      return;
    }
    for (const child of group.children) visit(unquoteXcodeValue(child.value), groupDirectory);
  };
  visit(mainGroupKey, mainDirectory);
  return found ?? { key: mainGroupKey, directory: mainDirectory };
}

/** The `InfoPlist.strings` variant group, when the project already has one. */
function findInfoPlistVariantGroup(project) {
  return xcodeSectionEntries(project, 'PBXVariantGroup')
    .find(({ object }) => unquoteXcodeValue(object.name) === IOS_VARIANT_GROUP_NAME) ?? null;
}

/** A file reference by its project-relative path, when one already exists. */
function findXcodeFileReference(project, relativePath) {
  // Matched exactly, because a `PBXFileReference` path is relative to the group that shows it:
  // a reference written for another group (e.g. Expo's `Supporting/en.lproj/...`) points at a
  // different file, and reusing it would register the wrong one. Only the path this plugin writes
  // for the group it attaches to is a candidate.
  return xcodeSectionEntries(project, 'PBXFileReference')
    .find(({ object }) => unquoteXcodeValue(object.path) === relativePath) ?? null;
}

/**
 * A localised `InfoPlist.strings` file reference, in the shape Xcode itself writes:
 * `name = <locale>` (the localisation Xcode lists) and `path = <locale>.lproj/InfoPlist.strings`.
 * `xcode` has no API for that shape — its `PBXFile` helper always derives `name` from the file
 * basename — so the object is added to the `PBXFileReference` section directly.
 */
function addLocalisedFileReference(project, locale, relativePath) {
  const key = project.generateUuid();
  const section = project.hash.project.objects.PBXFileReference;
  section[key] = {
    isa: 'PBXFileReference',
    fileEncoding: 4,
    lastKnownFileType: 'text.plist.strings',
    name: `"${locale}"`,
    path: `"${relativePath}"`,
    sourceTree: '"<group>"',
  };
  section[`${key}_comment`] = locale;
  return key;
}

/**
 * Register `<locale>.lproj/InfoPlist.strings` for every locale in the app's Xcode project.
 *
 * Idempotent by construction: an existing variant group is reused (never re-created), an
 * existing `<locale>.lproj/InfoPlist.strings` file reference is re-attached instead of
 * duplicated, at most one build file points at the variant group, and the Resources build
 * phase holds at most one entry for it. A plain (non-variant) registration of the same paths —
 * e.g. what an older plugin version left behind — is folded into the variant group and its
 * standalone build file removed, because two resource entries for the same destination make
 * Xcode fail with "Multiple commands produce .../InfoPlist.strings".
 *
 * @returns {{variantGroup: string, buildFile: string, parentGroup: string, locales: string[]}}
 */
function registerLocalisedInfoPlist(project, projectName, locales) {
  if (!projectName) throw new Error(`${PLUGIN_NAME}: iOS project name is unknown`);
  if (!/^[A-Za-z0-9_]+$/.test(projectName)) throw new Error(`${PLUGIN_NAME}: unexpected iOS project name`);
  const target = project.getTarget(APPLICATION_PRODUCT_TYPE);
  if (!target) {
    throw new Error(
      `${PLUGIN_NAME}: the Xcode project has no ${APPLICATION_PRODUCT_TYPE} target, so the localised ` +
        'InfoPlist.strings cannot be added to the app bundle',
    );
  }
  const resourcesPhase = project.pbxResourcesBuildPhaseObj(target.uuid);
  if (!resourcesPhase || !Array.isArray(resourcesPhase.files)) {
    throw new Error(
      `${PLUGIN_NAME}: the application target has no ${IOS_RESOURCES_BUILD_PHASE} build phase; ` +
        'the localised InfoPlist.strings cannot be bundled',
    );
  }
  const parent = locateIosAppGroup(project, projectName);

  // Xcode lists a localisation in `knownRegions`; the file reference alone is enough to copy it,
  // but the region keeps the project's localisation list correct.
  const projectSection = project.getFirstProject().firstProject;
  for (const locale of locales) {
    if (!XCODE_LOCALE_PATTERN.test(locale)) throw new Error(`${PLUGIN_NAME}: unsupported locale "${locale}"`);
    const regions = Array.isArray(projectSection.knownRegions) ? projectSection.knownRegions : [];
    if (!regions.some((region) => unquoteXcodeValue(region) === locale)) project.addKnownRegion(locale);
  }

  let variant = findInfoPlistVariantGroup(project);
  if (!variant) {
    const key = project.pbxCreateVariantGroup(IOS_VARIANT_GROUP_NAME);
    variant = { key, object: project.getPBXVariantGroupByKey(key) };
  }
  if (!Array.isArray(variant.object.children)) variant.object.children = [];
  const parentGroup = project.getPBXGroupByKey(parent.key);
  if (parentGroup && Array.isArray(parentGroup.children)
    && !parentGroup.children.some((child) => unquoteXcodeValue(child.value) === variant.key)) {
    parentGroup.children.push({ value: variant.key, comment: IOS_VARIANT_GROUP_NAME });
  }

  const localised = [];
  for (const locale of locales) {
    const projectRelative = `${projectName}/${locale}.lproj/${IOS_VARIANT_GROUP_NAME}`;
    const referencePath = path.posix.relative(parent.directory || '.', projectRelative) || projectRelative;
    const child = variant.object.children.find((entry) => unquoteXcodeValue(entry.comment) === locale);
    if (child) {
      localised.push({ locale, fileRef: unquoteXcodeValue(child.value) });
      continue;
    }
    const existing = findXcodeFileReference(project, referencePath);
    const fileRef = existing ? existing.key : addLocalisedFileReference(project, locale, referencePath);
    variant.object.children.push({ value: fileRef, comment: locale });
    localised.push({ locale, fileRef });
  }
  // One child per file reference, even if an older run appended the same one twice.
  const seenFileRefs = new Set();
  variant.object.children = variant.object.children.filter((child) => {
    const fileRef = unquoteXcodeValue(child.value);
    if (seenFileRefs.has(fileRef)) return false;
    seenFileRefs.add(fileRef);
    return true;
  });

  // Fold a plain (non-variant) registration of the same files into the variant group: removing
  // its build file prevents a duplicate copy of the same <locale>.lproj resource.
  const localisedFileRefs = new Set(localised.map((entry) => entry.fileRef));
  const buildFilesSection = project.hash.project.objects.PBXBuildFile;
  const removedBuildFiles = new Set();
  for (const { key, object } of xcodeSectionEntries(project, 'PBXBuildFile')) {
    const fileRef = unquoteXcodeValue(object.fileRef);
    if (fileRef === variant.key || !localisedFileRefs.has(fileRef)) continue;
    removedBuildFiles.add(key);
    delete buildFilesSection[key];
    delete buildFilesSection[`${key}_comment`];
  }
  if (removedBuildFiles.size > 0) {
    resourcesPhase.files = resourcesPhase.files.filter((file) => !removedBuildFiles.has(unquoteXcodeValue(file.value)));
  }

  // One build file for the variant group, one Resources entry for that build file.
  const variantBuildFiles = xcodeSectionEntries(project, 'PBXBuildFile')
    .filter(({ object }) => unquoteXcodeValue(object.fileRef) === variant.key);
  let buildFile = variantBuildFiles.length > 0 ? variantBuildFiles[0].key : null;
  for (const duplicate of variantBuildFiles.slice(1)) {
    delete buildFilesSection[duplicate.key];
    delete buildFilesSection[`${duplicate.key}_comment`];
    resourcesPhase.files = resourcesPhase.files.filter((file) => unquoteXcodeValue(file.value) !== duplicate.key);
  }
  if (!buildFile) {
    buildFile = project.generateUuid();
    project.addToPbxBuildFileSection({
      uuid: buildFile,
      fileRef: variant.key,
      basename: IOS_VARIANT_GROUP_NAME,
      group: IOS_RESOURCES_BUILD_PHASE,
      target: target.uuid,
    });
  }
  const buildFileEntries = resourcesPhase.files.filter((file) => unquoteXcodeValue(file.value) === buildFile);
  if (buildFileEntries.length === 0) {
    project.addToPbxResourcesBuildPhase({
      uuid: buildFile,
      fileRef: variant.key,
      basename: IOS_VARIANT_GROUP_NAME,
      group: IOS_RESOURCES_BUILD_PHASE,
      target: target.uuid,
    });
  } else if (buildFileEntries.length > 1) {
    let kept = false;
    resourcesPhase.files = resourcesPhase.files.filter((file) => {
      if (unquoteXcodeValue(file.value) !== buildFile) return true;
      if (kept) return false;
      kept = true;
      return true;
    });
  }

  return {
    variantGroup: variant.key,
    buildFile,
    parentGroup: parent.key,
    locales: localised.map((entry) => entry.locale),
  };
}

/** Resolve the effective permission strings for the requested locales. */
function resolvePermissionStrings(config, props) {
  const locales = Array.isArray(props.locales) && props.locales.length > 0 ? props.locales : ['en', 'vi'];
  const strings = { ...DEFAULT_PERMISSION_STRINGS, ...(props.strings ?? {}) };
  // English values must match what app.json declares, so `expo config` and the generated
  // en.lproj/InfoPlist.strings cannot disagree.
  const infoPlist = (config.ios && config.ios.infoPlist) || {};
  if (typeof infoPlist.NSCameraUsageDescription === 'string') {
    strings.en = { ...strings.en, NSCameraUsageDescription: infoPlist.NSCameraUsageDescription };
  }
  if (typeof infoPlist.NSFaceIDUsageDescription === 'string') {
    strings.en = { ...strings.en, NSFaceIDUsageDescription: infoPlist.NSFaceIDUsageDescription };
  }
  return { locales, strings };
}

