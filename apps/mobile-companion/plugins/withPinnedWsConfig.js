/**
 * @param {object} config Expo config (from app.json).
 * @param {{locales?: string[], strings?: Record<string, Record<string, string>>}} props
 */
function withPinnedWsConfig(config, props = {}) {
  assertNoCleartextOptIn(config);
  assertNoAtsOptIn(config);
  const resolved = resolvePermissionStrings(config, props ?? {});
  config = withAndroidNetworkSecurity(config);
  config = withAndroidNetworkSecurityFile(config);
  config = withAllowedTransportSecurityDefault(config);
  config = withLocalisedPermissionStrings(config, resolved);
  config = withLocalisedPermissionStringsRegistered(config, resolved);
  return config;
}

